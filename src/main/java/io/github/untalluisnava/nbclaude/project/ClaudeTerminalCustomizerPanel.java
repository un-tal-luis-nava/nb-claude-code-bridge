    /**
     * Shows a folder icon for directory entries, and a question-mark icon for
     * "Ask every time".
     */
    private static final class DirectoryOptionCellRenderer extends DefaultListCellRenderer {

        private static final int ICON_SIZE = 16;

        private final Icon folderIcon = scaled(UIManager.getIcon("FileView.directoryIcon"), ICON_SIZE);
        private final Icon questionIcon = scaled(UIManager.getIcon("OptionPane.questionIcon"), ICON_SIZE);

        @Override
        public Component getListCellRendererComponent(
                JList<?> list, Object value, int index, boolean isSelected, boolean cellHasFocus) {
            JLabel label
                    = (JLabel) super.getListCellRendererComponent(list, value, index, isSelected, cellHasFocus);
            label.setIcon(ASK_LABEL.equals(value) ? questionIcon : folderIcon);
            return label;
        }

        /**
         * Look-and-feel icons come in whatever native size that L&F ships (the
         * question-mark icon in particular is usually a large dialog-banner
         * icon), so they are rasterized to a common square size here instead of
         * being used as-is.
         */
        private static Icon scaled(Icon source, int size) {
            if (source == null) {
                return null;
            }
            BufferedImage buffer = new BufferedImage(
                    source.getIconWidth(), source.getIconHeight(), BufferedImage.TYPE_INT_ARGB);
            Graphics2D g = buffer.createGraphics();
            g.setRenderingHint(RenderingHints.KEY_INTERPOLATION, RenderingHints.VALUE_INTERPOLATION_BILINEAR);
            source.paintIcon(null, g, 0, 0);
            g.dispose();
            Image scaled = buffer.getScaledInstance(size, size, Image.SCALE_SMOOTH);
            return new ImageIcon(scaled);
        }
    }
