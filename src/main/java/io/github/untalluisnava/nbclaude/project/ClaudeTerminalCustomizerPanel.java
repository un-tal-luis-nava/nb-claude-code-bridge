    /**
     * Populates the combo with {@code candidates} (project directory first,
     * then ancestor directories that contain a {@code .claude} folder, closest
     * first) plus an "Ask every time" entry, and preselects {@code storedValue}
     * (an absolute path, {@link
     * ClaudeTerminalDirectoryPreference#ASK}, or {@code null} for the computed
     * default).
     */
    public void setCandidates(List<File> candidates, String storedValue) {
        this.candidates = candidates;
        List<String> items = new ArrayList<>();
        for (int i = 0; i < candidates.size(); i++) {
            File candidate = candidates.get(i);
            String prefix = i == 0 ? "This project: " : "Ancestor (.claude): ";
            items.add(prefix + candidate.getAbsolutePath());
        }
        items.add(ASK_LABEL);
        directoryModeComboBox.setModel(new DefaultComboBoxModel<>(items.toArray(new String[0])));
        directoryModeComboBox.setSelectedIndex(resolveSelectedIndex(candidates, storedValue));
    }

    private int resolveSelectedIndex(List<File> candidates, String storedValue) {
        if (storedValue == null) {
            // Mirrors ClaudeTerminalDirectoryPreference's computed default: only default to "Ask"
            // when there is an actual choice beyond the project's own folder.
            return candidates.size() > 1 ? candidates.size() : 0;
        }
        if (ClaudeTerminalDirectoryPreference.ASK.equals(storedValue)) {
            return candidates.size();
        }
        for (int i = 0; i < candidates.size(); i++) {
            if (candidates.get(i).getAbsolutePath().equals(storedValue)) {
                return i;
            }
        }
        return candidates.size(); // the remembered directory is no longer a candidate
    }

    /**
     * The value to persist: an absolute path, or
     * {@link ClaudeTerminalDirectoryPreference#ASK}.
     */
    public String getSelectedValue() {
        int index = directoryModeComboBox.getSelectedIndex();
        if (index < 0 || index >= candidates.size()) {
            return ClaudeTerminalDirectoryPreference.ASK;
        }
        return candidates.get(index).getAbsolutePath();
    }

